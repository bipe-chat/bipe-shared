// The feature map (bipe-chat/bipe#1619): how the marketed features (product/product.json), the capabilities
// (product/parity.json) and the screen specs (product/screens/) connect, with the status of each capability
// per surface. tools/gen-feature-map.mjs writes it to bipe/docs/feature-map.md. Pure functions, no file access.

export const SURFACES = ["ios", "android", "web", "server", "macos", "windows"];
const LABEL = { ios: "iOS", android: "Android", web: "Web", server: "Server", macos: "Mac", windows: "Windows" };
const CODE = { testing: "T", built: "B", planned: "P", policy: "X", "n/a": "-" };
const COUNTED = ["testing", "built", "planned", "policy", "n/a"];

// A surface value is a status string or { status, evidence?, reason?, issue? }.
export const surfaceStatus = (item, s) => (typeof item[s] === "string" ? item[s] : item[s]?.status);

// A capability that the phone app does not show (server-only, or a policy such as "Free") needs no screen.
export const needsNoScreen = (item) => ["ios", "android"].every((s) => ["policy", "n/a"].includes(surfaceStatus(item, s)));

// parity id -> ids of the screens that list it, in screen id order.
export function screensByCapability(screens) {
  const out = new Map();
  for (const s of [...screens].sort((a, b) => a.id.localeCompare(b.id))) {
    for (const id of s.parity ?? []) out.set(id, [...(out.get(id) ?? []), s.id]);
  }
  return out;
}

// The loose ends: capabilities that need a screen and are on none, and screens that list no capability.
export function looseEnds(items, screens) {
  const served = screensByCapability(screens);
  const onNoScreen = items.filter((i) => !served.has(i.id));
  return {
    onNoScreen: onNoScreen.filter((i) => !needsNoScreen(i)).map((i) => i.id),
    exempt: onNoScreen.filter(needsNoScreen).map((i) => i.id),
    noCapability: screens.filter((s) => !(s.parity ?? []).length).map((s) => s.id).sort(),
  };
}

const cell = (text) => String(text ?? "").replaceAll("|", "/").replace(/\s*\n\s*/g, " ");
const ids = (list) => list.map((id) => `\`${id}\``).join(", ");
const code = (item, s) => CODE[surfaceStatus(item, s)] ?? surfaceStatus(item, s) ?? "?";

// product: product/product.json. items: product/parity.json items. screens: the screen specs.
// source: optional line that says where the text came from (the commit, for the copy outside the repo).
export function featureMap({ product, items, screens, source }) {
  const byFeature = new Map(product.features.map((f) => [f.id, f]));
  const byItem = new Map(items.map((i) => [i.id, i]));
  const screenById = new Map(screens.map((s) => [s.id, s]));
  const served = screensByCapability(screens);
  const head = SURFACES.map((s) => LABEL[s]).join(" | ");
  const rule = SURFACES.map(() => "---|").join("");
  const lines = [];
  const w = (...l) => lines.push(...l);

  w("# Feature map: Bipe", "");
  w("Generated by `bipe-shared/tools/gen-feature-map.mjs` from `bipe-shared/product/product.json`, `product/parity.json` and `product/screens/*.json`. Do not edit here: change the JSON and run the generator. When a row here disagrees with the registries, the registries win.");
  if (source) w("", source);
  w("");
  w("**Status** comes from the parity ledger (ADR 0092): **T** testing (in a tester build) · **B** built (merged, not in a tester build) · **P** planned (an issue names the work) · **X** policy (left out on purpose) · **-** does not apply on that surface. Surfaces: iOS and Android (bipe-app), Web (bipe-web, bipe-app web), Server (bipe-api, bipe-infra), Mac and Windows (desktop).", "");

  w("## 1. How the pieces connect", "");
  w("```");
  w("product.json   - marketed features (site, store copy), areas, tentpoles");
  w("      | same id");
  w("parity.json    - every capability, status per surface, evidence paths, open issue");
  w("      | screen.parity[]");
  w("screens/*.json - one spec per screen: flow, state, actions, strings, sdk calls");
  w("      | same id in code");
  w("bipe-app iOS (SwiftUI), Android (Compose), web, macOS, Windows");
  w("```", "");
  w("- A **marketed feature** is a capability that the site and the store talk about. Its status is the status of the parity item with the same id.");
  w("- A **capability** (parity item) can serve several screens. A screen serves zero or more capabilities.");
  w("- A **screen** belongs to one flow (launch, signup, home, chat, groups, business, settings and others).", "");

  w("## 2. Status at a glance", "");
  w(`| Surface | ${COUNTED.join(" | ")} |`, `|---|${COUNTED.map(() => "---|").join("")}`);
  for (const s of SURFACES) w(`| ${LABEL[s]} | ${COUNTED.map((st) => items.filter((i) => surfaceStatus(i, s) === st).length).join(" | ")} |`);
  w("", `${product.features.length} marketed features, ${items.length} capabilities, ${screens.length} screens.`, "");

  w("## 3. Tentpoles", "");
  w("| Tentpole | Status | Features |", "|---|---|---|");
  for (const t of product.tentpoles) w(`| **${cell(t.en?.name)}** (\`${t.id}\`) | ${t.status ?? ""} | ${ids(t.features ?? [])} |`);
  w("");

  w("## 4. Marketed features", "");
  for (const area of product.areas) {
    const features = product.features.filter((f) => f.area === area.id);
    if (!features.length) continue;
    w(`### ${area.en}`, "");
    w(`| ID | Feature | What a person gets | ${head} | Screens |`, `|---|---|---|${rule}---|`);
    for (const f of features) {
      const item = byItem.get(f.id);
      const codes = SURFACES.map((s) => (item ? code(item, s) : "?")).join(" | ");
      w(`| \`${f.id}\` | ${cell(f.en?.name)} | ${cell(f.en?.body)} | ${codes} | ${ids(served.get(f.id) ?? []) || "none"} |`);
    }
    w("");
  }

  w("## 5. Other capabilities", "");
  w("Capabilities that are not marketed features (section 4 has those), grouped by the flow of the first screen that serves them.", "");
  const groups = new Map();
  for (const item of items) {
    if (byFeature.has(item.id)) continue;
    const first = served.get(item.id)?.[0];
    const group = first ? `Flow: ${screenById.get(first).flow}` : "Not on a screen";
    groups.set(group, [...(groups.get(group) ?? []), item]);
  }
  const order = [...groups.keys()].sort((a, b) => (a === "Not on a screen") - (b === "Not on a screen") || a.localeCompare(b));
  for (const group of order) {
    w(`### ${group}`, "");
    w(`| ID | Capability | ${head} | Open issue |`, `|---|---|${rule}---|`);
    for (const item of groups.get(group).sort((a, b) => a.id.localeCompare(b.id))) {
      w(`| \`${item.id}\` | ${cell(item.name)} | ${SURFACES.map((s) => code(item, s)).join(" | ")} | ${item.issue ? `#${item.issue}` : ""} |`);
    }
    w("");
  }

  w("## 6. Screens by flow", "");
  w("Each screen spec in `bipe-shared/product/screens/<id>.json` holds its state, actions, strings and the capabilities it serves. Sections 4 and 5 list the screens of each capability.", "");
  const flows = new Map();
  for (const s of [...screens].sort((a, b) => a.id.localeCompare(b.id))) flows.set(s.flow, [...(flows.get(s.flow) ?? []), s.id]);
  for (const [flow, list] of [...flows].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]))) {
    w(`- **${flow}** (${list.length}): ${ids(list)}`);
  }
  w("");

  w("## 7. Loose ends", "");
  const ends = looseEnds(items, screens);
  w(`- **Capabilities on no screen** (${ends.onNoScreen.length}): ${ids(ends.onNoScreen) || "none"}. A background capability, or a screen spec that does not list it yet.`);
  w(`- **Screens that serve no capability** (${ends.noCapability.length}): ${ids(ends.noCapability) || "none"}.`);
  w(`- **Need no screen** (${ends.exempt.length}): server-only or policy on both apps: ${ids(ends.exempt) || "none"}.`);
  const missing = product.features.filter((f) => !byItem.has(f.id)).map((f) => f.id);
  if (missing.length) w(`- **Marketed features with no ledger item**: ${ids(missing)}.`);
  w("");
  w("Check: `node tools/screens.mjs` warns for a screen with no capability. `node tools/parity.mjs --report` lists the capabilities on no screen.", "");
  return lines.join("\n");
}
