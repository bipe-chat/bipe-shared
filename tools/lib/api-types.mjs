import { readFileSync } from "node:fs";
import { join } from "node:path";

// JSON Schema is also an OpenAPI 3.1 schema. The contract and API types share these definitions.
export function loadBusinessSchemas(root) {
  const { $defs: schemas } = JSON.parse(readFileSync(join(root, "api/business-schemas.json"), "utf8"));
  if (!schemas || !Object.keys(schemas).length) throw new Error("business-schemas.json: missing $defs");
  for (const name of Object.keys(schemas)) {
    if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) throw new Error(`invalid schema name: ${name}`);
  }
  const walk = (value) => {
    if (!value || typeof value !== "object") return;
    if (value.$ref && (!value.$ref.startsWith("#/$defs/") || !schemas[value.$ref.slice(8)])) {
      throw new Error(`unresolved business schema: ${value.$ref}`);
    }
    Object.values(value).forEach(walk);
  };
  walk(schemas);
  return schemas;
}

export function schemaType(schema) {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  const parts = [];
  if (schema.$ref) {
    if (!/^#\/\$defs\/[A-Z][A-Za-z0-9]*$/.test(schema.$ref)) throw new Error(`unsupported type reference: ${schema.$ref}`);
    const name = schema.$ref.slice(8);
    parts.push(name);
    if (schema.required?.length) parts.push(`Required<Pick<${name}, ${schema.required.map((key) => JSON.stringify(key)).join(" | ")}>>`);
  }
  if (schema.const !== undefined) parts.push(JSON.stringify(schema.const));
  else if (schema.enum) parts.push(`(${schema.enum.map((value) => JSON.stringify(value)).join(" | ")})`);
  else if (schema.type === "object" || schema.properties) {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([key, value]) => {
      const comment = value.description ? `/** ${value.description.replaceAll("*/", "* / ")} */ ` : "";
      return `${comment}${JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${schemaType(value)}`;
    });
    if (schema.additionalProperties && schema.additionalProperties !== false) {
      if (fields.length) throw new Error("open objects with named fields are not supported by the type generator");
      parts.push(`Record<string, ${schemaType(schema.additionalProperties)}>`);
    } else parts.push(fields.length ? `{ ${fields.join("; ")} }` : "Record<string, never>");
  } else if (schema.type === "array") {
    if (!schema.items) throw new Error("array schema needs items");
    parts.push(`Array<${schemaType(schema.items)}>`);
  } else if (schema.type) {
    const types = { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null" };
    if (Array.isArray(schema.type)) parts.push(`(${schema.type.map((type) => schemaType({ type })).join(" | ")})`);
    else if (types[schema.type]) parts.push(types[schema.type]);
    else throw new Error(`unsupported schema type: ${schema.type}`);
  }
  if (schema.allOf) parts.push(...schema.allOf.map(schemaType));
  for (const union of [schema.oneOf, schema.anyOf]) if (union) parts.push(`(${union.map(schemaType).join(" | ")})`);
  // Format, ranges and conditional validation are enforced by JSON Schema, not TypeScript.
  return parts.filter((part) => part !== "unknown").join(" & ") || "unknown";
}

export function generateApiTypes(schemas) {
  return "// Generated by bipe-shared/tools/gen.mjs. Do not edit.\n" +
    "// Source: bipe-shared/api/business-schemas.json (OpenAPI 3.1 / JSON Schema 2020-12).\n" +
    "// These types describe the contract. Routes may still be planned; see the parity ledger.\n\n" +
    Object.entries(schemas).map(([name, schema]) => {
      const comment = schema.description ? `/** ${schema.description.replaceAll("*/", "* / ")} */\n` : "";
      return `${comment}export type ${name} = ${schemaType(schema)};\n`;
    }).join("\n");
}
