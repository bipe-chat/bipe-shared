// Android string resource escaping. %N$s placeholders stay as they are.
const androidString = (v) => {
  const esc = v
    .replace(/\\/g, "\\\\")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
  return /^[@?]/.test(esc) ? `\\${esc}` : esc;
};

