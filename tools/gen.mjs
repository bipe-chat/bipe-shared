// Apple .strings syntax; %N$s placeholders become %N$@ (Swift String arguments).
const appleStrings = (strings) =>
  HEADER.replace(/^\/\//gm, "/*").replace(/\n/g, " */\n") +
  Object.entries(strings).map(([k, v]) => {
    const esc = v.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/%(\d+)\$s/g, "%$1$$@");
    return `"${k}" = "${esc}";`;
  }).join("\n") + "\n";

function swiftStrings() {
  const members = Object.entries(reg.strings.strings).map(([key, value]) => {
    const placeholders = [...new Set([...value.matchAll(/%(\d+)\$s/g)].map((m) => Number(m[1])))].sort();
    const lookup = `NSLocalizedString(${swiftString(key)}, tableName: "Bipe", bundle: .module, comment: "")`;
    if (placeholders.length === 0) return `    public static var ${camel(key)}: String { ${lookup} }`;
    const params = placeholders.map((n) => `_ p${n}: String`).join(", ");
    const args = placeholders.map((n) => `p${n}`).join(", ");
    return `    public static func ${camel(key)}(${params}) -> String {\n        String(format: ${lookup}, ${args})\n    }`;
  });
  return `${HEADER}
import Foundation

// pt-BR is the default language; en is the alternative (Resources/<locale>.lproj/Bipe.strings).
// DRAFT copy: not yet through the humanizer pass.
public enum BipeStrings {
${members.join("\n\n")}
}
`;
}

// Writes the BipeKit Swift files and string tables. `out` is <package>/Sources/BipeKit/Generated.
// `post` rewrites each file for the target (bipe-app adds its licence header); `cast` writes BipeCast.swift.
function writeSwift(out, { post = (text) => text, cast = true } = {}) {
  const write = (file, text) => writeFileSync(join(out, file), post(text, "swift"));
  mkdirSync(out, { recursive: true });
  write("BipeRegistries.swift", swiftRegistries());
  write("BipeTrustFacts.swift", generateTrust(reg.trust, "swift", HEADER));
  write("BipeChatArchive.swift", generateChatArchive("swift", HEADER));
  write("BipeDmSelection.swift", generateDmSelection(reg.dmSelection, "swift", HEADER));
  write("BipeRelationshipNames.swift", generateRelationshipNames(reg.relationshipNames, "swift", HEADER));
  write("BipeAgendaTemplates.swift", generateAgendaTemplates(reg, "swift", HEADER));
  write("BipeStrings.swift", swiftStrings());
  write("BipeSettings.swift", generateSettings(reg.settings, "swift", HEADER, swiftString));
  write("BipeOnboarding.swift", generateOnboarding(reg.onboarding, "swift", HEADER, swiftString));
  write("BipeHaptics.swift", generateHaptics(reg.haptics, "swift", HEADER, swiftString));
  if (cast) write("BipeCast.swift", generateCast(loadCast(root), CAST_HEADER, swiftString));
  const resources = resolve(out, "../../../Sources/BipeKit/Resources");
  for (const [locale, strings] of [["pt-BR", reg.strings.strings], ["en", reg.stringsEn.strings]]) {
    mkdirSync(join(resources, `${locale}.lproj`), { recursive: true });
    writeFileSync(join(resources, `${locale}.lproj`, "Bipe.strings"), appleStrings(strings));
  }
  console.log(`wrote Swift to ${out}`);
}
writeSwift(swiftOut);

