// Generates platform code from registries/ and strings/.
// Usage: node tools/gen.mjs --swift <output dir>
//   Default Swift output: ../proseio-ios/Components/ProseioKit/Sources/ProseioKit/Generated
// Kotlin output is added when the Android mirror starts.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadRegistries } from "./lib/registries.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const swiftIndex = args.indexOf("--swift");
const swiftOut = resolve(swiftIndex >= 0 ? args[swiftIndex + 1] : join(root, "../proseio-ios/Components/ProseioKit/Sources/ProseioKit/Generated"));

const reg = loadRegistries(root);
const HEADER = "// Generated by proseio-shared/tools/gen.mjs. Do not edit.\n// Source of truth: proseio-shared/registries and proseio-shared/strings.\n";

const swiftString = (s) =>
  '"' + [...s].map((c) => {
    if (c === "\\") return "\\\\";
    if (c === '"') return '\\"';
    const code = c.codePointAt(0);
    if (code < 0x20 || code === 0x7f) return `\\u{${code.toString(16)}}`;
    return c;
  }).join("") + '"';

const camel = (key) => key.replace(/^proseio_/, "").replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const swiftArray = (items, indent = "        ") => "[\n" + items.map((i) => `${indent}${i},`).join("\n") + `\n${indent.slice(4)}]`;

function swiftRegistries() {
  const reserved = Object.entries(reg.reserved.categories).flatMap(([cat, names]) => names.map((n) => `${swiftString(n)}: .${cat}`));
  const categories = Object.keys(reg.reserved.categories).map((c) => `    case ${c}`).join("\n");
  const patterns = (group) => swiftArray(reg.scam[group].map((p) => `ScamPattern(id: ${swiftString(p.id)}, regex: ${swiftString(p.regex)})`));
  const homoglyphs = Object.entries(reg.homoglyphs.map).map(([k, v]) => `${swiftString(k)}: ${swiftString(v)}`);

  return `${HEADER}
public enum ReservedNameCategory: String, Sendable {
${categories}
}

public struct ScamPattern: Sendable, Equatable {
    public let id: String
    public let regex: String
}

public enum ProseioRegistries {
    /// Normalised reserved display names and their category.
    public static let reservedNames: [String: ReservedNameCategory] = ${swiftArray(reserved)}

    /// Normalised relationship terms that trigger the name-mismatch check.
    public static let familyTerms: Set<String> = ${swiftArray(reg.family.terms.map(swiftString))}

    /// Character folding applied after lowercasing and diacritic stripping.
    public static let homoglyphs: [Character: Character] = ${swiftArray(homoglyphs)}

    public static let pixKeyPatterns: [ScamPattern] = ${patterns("pixKeyPatterns")}

    public static let pixCopyPastePatterns: [ScamPattern] = ${patterns("pixCopyPastePatterns")}

    public static let boletoPatterns: [ScamPattern] = ${patterns("boletoPatterns")}

    /// Normalised phrases, matched as substrings of the normalised message.
    public static let urgencyPhrases: [String] = ${swiftArray(reg.scam.urgencyPhrases.map(swiftString))}

    /// Normalised keywords, matched as substrings of the normalised message.
    public static let receiptKeywords: [String] = ${swiftArray(reg.scam.receiptKeywords.map(swiftString))}
}
`;
}

function swiftStrings() {
  const members = Object.entries(reg.strings.strings).map(([key, value]) => {
    const placeholders = [...new Set([...value.matchAll(/%(\d+)\$s/g)].map((m) => Number(m[1])))].sort();
    if (placeholders.length === 0) return `    public static let ${camel(key)} = ${swiftString(value)}`;
    const params = placeholders.map((n) => `_ p${n}: String`).join(", ");
    let body = swiftString(value);
    for (const n of placeholders) body = body.replaceAll(`%${n}$s`, `\\(p${n})`);
    return `    public static func ${camel(key)}(${params}) -> String {\n        ${body}\n    }`;
  });
  return `${HEADER}
// pt-BR only for now. DRAFT copy: not yet through the humanizer pass.
public enum ProseioStrings {
${members.join("\n\n")}
}
`;
}

mkdirSync(swiftOut, { recursive: true });
writeFileSync(join(swiftOut, "ProseioRegistries.swift"), swiftRegistries());
writeFileSync(join(swiftOut, "ProseioStrings.swift"), swiftStrings());
console.log(`wrote Swift to ${swiftOut}`);
