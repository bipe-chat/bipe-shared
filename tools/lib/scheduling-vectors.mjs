import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export function loadSchedulingVectors(root) {
  const bytes = readFileSync(join(root, "test-vectors/scheduling.json"));
  const document = JSON.parse(bytes);
  validateSchedulingVectors(document);
  return document;
}

// Check oracle structure and public-output privacy, not availability: the API must earn these answers.
export function validateSchedulingVectors(document) {
  assert.equal(document.version, 1);
  assert.ok(Array.isArray(document.vectors) && document.vectors.length > 0);
  const names = new Set();
  for (const vector of document.vectors) {
    assert.match(vector.name, /^[a-z0-9-]+$/);
    assert.ok(!names.has(vector.name), `duplicate scheduling vector: ${vector.name}`);
    names.add(vector.name);
    assert.ok(typeof vector.description === "string" && vector.description.length > 0 && !vector.description.includes("\n"));
    const { input, expected } = vector;
    const formatter = new Intl.DateTimeFormat("en-CA", { timeZone: input.time_zone, year: "numeric", month: "2-digit", day: "2-digit" });
    assert.equal(expected.slots.time_zone, input.time_zone);
    assert.deepEqual(Object.keys(expected.slots).sort(), ["days", "time_zone"]);
    const from = Date.parse(`${input.date_from}T00:00:00Z`);
    const to = Date.parse(`${input.date_to}T00:00:00Z`);
    assert.ok(Number.isFinite(from) && Number.isFinite(to) && from <= to && to - from < 366 * 86400000);
    assert.equal(expected.slots.days.length, (to - from) / 86400000 + 1);
    const starts = new Set();
    for (const [i, day] of expected.slots.days.entries()) {
      assert.deepEqual(Object.keys(day).sort(), ["date", "slots"]);
      assert.equal(day.date, new Date(from + i * 86400000).toISOString().slice(0, 10));
      let previous = -Infinity;
      for (const slot of day.slots) {
        assert.deepEqual(Object.keys(slot).sort(), ["end", "start"]);
        const start = Date.parse(slot.start);
        const end = Date.parse(slot.end);
        assert.equal(new Date(start).toISOString(), slot.start);
        assert.equal(new Date(end).toISOString(), slot.end);
        assert.ok(start > previous, `${vector.name}: slots must be unique and sorted`);
        previous = start;
        const parts = Object.fromEntries(formatter.formatToParts(start).map(({ type, value }) => [type, value]));
        assert.equal(`${parts.year}-${parts.month}-${parts.day}`, day.date);
        const service = input.services.find((item) => item.id === input.service_id);
        assert.equal(end - start, service.duration_minutes * 60000);
        starts.add(slot.start);
      }
    }
    assert.ok(Array.isArray(expected.picks));
    for (const pick of expected.picks) {
      assert.deepEqual(Object.keys(pick).sort(), ["agenda_id", "start"]);
      assert.equal(new Date(pick.start).toISOString(), pick.start);
      if (pick.agenda_id === null) continue;
      assert.ok(starts.has(pick.start), `${vector.name}: a chosen agenda needs a free slot`);
      assert.ok(input.agendas.some((agenda) => agenda.id === pick.agenda_id && agenda.active));
      assert.ok(input.services.find((service) => service.id === input.service_id)?.agenda_ids.includes(pick.agenda_id));
    }
  }
}

export function writeSchedulingApiFixture(root, out) {
  const source = readFileSync(join(root, "test-vectors/scheduling.json"));
  const { version, vectors } = loadSchedulingVectors(root);
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "scheduling.json"), JSON.stringify({
    $comment: "Generated by bipe-shared/tools/gen-test-vectors.mjs from test-vectors/scheduling.json. Do not edit.",
    source_sha256: createHash("sha256").update(source).digest("hex"),
    version, vectors,
  }, null, 2) + "\n");
}
